import json
from pathlib import Path

notebook_path = Path("specviz_full_pipeline.ipynb")
with open(notebook_path, "r") as f:
    nb = json.load(f)

# The new parallelized source code
new_source = [
    "print(\"🎨 Generating mirror plots...\")\n",
    "print(f\"   Max plots: {max_plots if max_plots else 'all'}\")\n",
    "print(f\"   Save to disk: {save_plots}\")\n",
    "print(f\"   Using create_matplotlib_mirror_plot() from spectrum_engine.py (thread-safe)\")\n",
    "\n",
    "import concurrent.futures\n",
    "import threading\n",
    "from functools import partial\n",
    "\n",
    "# Thread-safe counter for limiting display\n",
    "display_lock = threading.Lock()\n",
    "displayed_count = 0\n",
    "MAX_DISPLAY = 20  # Limit browser rendering to prevents crashes\n",
    "\n",
    "plot_count = 0\n",
    "missing_ref = 0\n",
    "missing_upper = 0\n",
    "missing_lower = 0\n",
    "\n",
    "# Ensure output directory exists\n",
    "if save_plots:\n",
    "    plot_output_dir.mkdir(parents=True, exist_ok=True)\n",
    "\n",
    "def process_single_plot(row_data):\n",
    "    \"\"\"Worker function to process a single plot.\"\"\"\n",
    "    idx, row = row_data\n",
    "    result = {\n",
    "        'success': False,\n",
    "        'missing_ref': False,\n",
    "        'missing_upper': False,\n",
    "        'missing_lower': False,\n",
    "        'fig': None,\n",
    "        'filename': None\n",
    "    }\n",
    "    \n",
    "    # Skip if this IS from a reference mzML file\n",
    "    if row[\"mzml_file\"] in reference_mzml_names:\n",
    "        return result\n",
    "    \n",
    "    # Find reference row\n",
    "    ref_row = pick_reference_row(row)\n",
    "    if ref_row is None:\n",
    "        result['missing_ref'] = True\n",
    "        return result\n",
    "    \n",
    "    # Load upper spectrum (sample)\n",
    "    upper_spec = load_spectrum_from_experiment(experiments, lookups, row[\"mzml_file\"], row[\"spectrum_id\"])\n",
    "    if upper_spec is None:\n",
    "        result['missing_upper'] = True\n",
    "        return result\n",
    "    \n",
    "    # Load lower spectrum (reference)\n",
    "    lower_spec = load_spectrum_from_experiment(experiments, lookups, ref_row[\"mzml_file\"], ref_row[\"spectrum_id\"])\n",
    "    if lower_spec is None:\n",
    "        result['missing_lower'] = True\n",
    "        return result\n",
    "    \n",
    "    # Annotate spectra\n",
    "    upper_df = annotate_spectrum_with_theoretical(\n",
    "        upper_spec,\n",
    "        row[\"peptide_sequence\"],\n",
    "        charge=row.get(\"charge\"),\n",
    "        tol=fragment_mass_tolerance, included_ions=ion_types\n",
    "    )\n",
    "    \n",
    "    lower_df = annotate_spectrum_with_theoretical(\n",
    "        lower_spec,\n",
    "        ref_row[\"peptide_sequence\"],\n",
    "        charge=ref_row.get(\"charge\"),\n",
    "        tol=fragment_mass_tolerance, included_ions=ion_types\n",
    "    )\n",
    "    \n",
    "    # Create plot title\n",
    "    ref_display = ref_row['run'] if 'run' in ref_row else Path(ref_row['mzml_file']).stem\n",
    "    title = (\n",
    "        f\"{row['run']} {row['peptide_sequence']} (source: {row['idxml_source']})\\n\"\n",
    "        f\"Reference: {ref_display}\"\n",
    "    )\n",
    "    \n",
    "    # Create mirror plot (Thread-safe Figure object)\n",
    "    fig = create_matplotlib_mirror_plot(\n",
    "        upper_df,\n",
    "        lower_df,\n",
    "        upper_colors=EXP_COLORS,\n",
    "        lower_colors=EXP_COLORS,\n",
    "        title=title,\n",
    "        upper_label=\"Sample\",\n",
    "        lower_label=\"Reference\",\n",
    "    )\n",
    "    \n",
    "    if fig is None:\n",
    "        return result\n",
    "    \n",
    "    result['success'] = True\n",
    "    result['fig'] = fig\n",
    "    \n",
    "    # Save plot if requested\n",
    "    if save_plots:\n",
    "        clean_spec_id = row['spectrum_id'].replace('/', '_').replace('\\\\', '_').replace('=', '_')\n",
    "        filename_base = f\"{row['run']}_{clean_spec_id}\"\n",
    "        export_matplotlib_mirror_plot(fig, str(plot_output_dir), filename_base)\n",
    "        result['filename'] = filename_base\n",
    "    \n",
    "    return result\n",
    "\n",
    "# Prepare rows for processing\n",
    "rows_to_process = []\n",
    "for idx, row in mapping_df.iterrows():\n",
    "    rows_to_process.append((idx, row))\n",
    "    if max_plots is not None and len(rows_to_process) >= max_plots:\n",
    "        break\n",
    "\n",
    "print(f\"   Processing {len(rows_to_process)} plots in parallel...\")\n",
    "\n",
    "# Run in parallel\n",
    "with concurrent.futures.ThreadPoolExecutor() as executor:\n",
    "    futures = {executor.submit(process_single_plot, item): item for item in rows_to_process}\n",
    "    \n",
    "    for future in concurrent.futures.as_completed(futures):\n",
    "        try:\n",
    "            res = future.result()\n",
    "            \n",
    "            if res['missing_ref']: missing_ref += 1\n",
    "            if res['missing_upper']: missing_upper += 1\n",
    "            if res['missing_lower']: missing_lower += 1\n",
    "            \n",
    "            if res['success']:\n",
    "                plot_count += 1\n",
    "                \n",
    "                # Thread-safe display limiting\n",
    "                with display_lock:\n",
    "                    if displayed_count < MAX_DISPLAY:\n",
    "                        display(res['fig'])\n",
    "                        displayed_count += 1\n",
    "                    elif displayed_count == MAX_DISPLAY:\n",
    "                        print(f\"... Display limit reached ({MAX_DISPLAY}), remaining plots saved to disk but not shown ...\")\n",
    "                        displayed_count += 1\n",
    "                \n",
    "                # Close figure to free memory if not displayed or after display\n",
    "                # (Local figure, so we don't need plt.close(), just let garbage collector handle it or explicit clf)\n",
    "                # res['fig'].clf() # Already cleared in export function if exported\n",
    "                pass \n",
    "                \n",
    "        except Exception as e:\n",
    "            print(f\"   ❌ Error in plot worker: {e}\")\n",
    "\n",
    "print(f\"\\n✅ Rendered {plot_count} mirror plot(s)\")\n",
    "print(f\"   Missing reference rows: {missing_ref}\")\n",
    "print(f\"   Missing upper spectra: {missing_upper}\")\n",
    "print(f\"   Missing lower spectra: {missing_lower}\")\n",
    "\n",
    "if save_plots and plot_count > 0:\n",
    "    print(f\"\\n💾 Plots saved to: {plot_output_dir}\")\n"
]

patched = False
for cell in nb["cells"]:
    if cell["cell_type"] == "code":
        source = cell["source"]
        if any("print(\"🎨 Generating mirror plots...\")" in line for line in source):
            cell["source"] = new_source
            patched = True
            break

if patched:
    with open(notebook_path, "w") as f:
        json.dump(nb, f, indent=1)
    print("✅ Notebook patched successfully.")
else:
    print("❌ Could not find the target cell to patch.")
